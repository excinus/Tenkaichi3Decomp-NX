/*
 * Switch spike: answers, on a real console, the three questions the Switch port depends on
 * (docs/port/switch_plan.md, phase 1). It does not run the game.
 *
 *   1. Memory. The game's pointers are 4 bytes: the 64-bit builds keep the PS2's memory in a 4 GB window, each
 *      region at window + its PS2 address, and the program itself at window + 0x20000000 (docs/port/macos_plan.md).
 *      Horizon gives no mmap at a chosen address; the port would map the regions with svcMapProcessCodeMemory and
 *      svcSetProcessMemoryPermission, as homebrew loaders map a program. This finds a free 4 GB-aligned window,
 *      maps the regions of port/src/plat_mem.c there, writes and reads them, and runs code mapped at
 *      window + 0x20000000.
 *   2. Speed. The game does all its float arithmetic in software (port/src/softfloat_ps2.c); bench.c times it, and
 *      the same file built on a PC gives the number to compare with.
 *   3. Pictures. The port's OpenGL renderer (port/src/gs/gs_gl.c, GL 3.3 core) on the console's Mesa (nouveau):
 *      a 3.3 core context, and every program of gs_gl.c compiled and linked from the port's own shaders.
 *
 * Results are shown on the screen and written to sdmc:/switch/bt3_spike.txt. Start it from the homebrew menu,
 * preferably through a game (hold R while starting one) so that it runs as an application with the full memory;
 * from the album it has less memory and the window test maps less.
 */
