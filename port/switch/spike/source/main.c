#include "spike_shaders.h" /* generated by gen_shaders.py from port/src/gs/shaders */

#define LOG_PATH "sdmc:/switch/bt3_spike.txt"
#define GB4 0x100000000ull
#define WINDOW_FIXED 0x4000000000ull /* 256 GB: a fixed choice the port could link against (see the plan) */

static char sLog[32768];
static size_t sLogLen;
static int sConsole;

static void say(const char *fmt, ...) {
    va_list ap;
    int n;

    va_start(ap, fmt);
    n = vsnprintf(sLog + sLogLen, sizeof(sLog) - sLogLen, fmt, ap);
    va_end(ap);
    if (n > 0 && sLogLen + (size_t)n < sizeof(sLog)) {
        if (sConsole) {
            fputs(sLog + sLogLen, stdout);
            consoleUpdate(NULL);
        }
        sLogLen += (size_t)n;
    }
}

uint64_t Bench_NowNs(void) {
    return armTicksToNs(armGetSystemTick());
}

static uint64_t info(uint32_t id) {
    uint64_t v = 0;

    if (R_FAILED(svcGetInfo(&v, id, CUR_PROCESS_HANDLE, 0))) {
        return 0;
    }
    return v;
}

/* ---- 1. the window ------------------------------------------------------------------------------------ */

typedef struct Region {
    uint32_t addr, size;
    const char *what;
    void *src;
    int mapped;
} Region;

/* port/src/plat_mem.c's regions (the low arena, 192 MB of address space on the PCs, is tried with 16 MB here) */
static Region sRegions[] = {
    {0x003BE000u, 0x02000000u - 0x003BE000u, "game heap", NULL, 0},
    {0x02000000u, 0x01000000u, "game stack", NULL, 0},
    {0x10000000u, 0x00010000u, "hardware registers", NULL, 0},
    {0x12000000u, 0x00002000u, "GS registers", NULL, 0},
    {0x13000000u, 0x01000000u, "low arena (16 of 192 MB)", NULL, 0},
    {0x70000000u, 0x00004000u, "scratchpad", NULL, 0},
};
#define NREGIONS (sizeof(sRegions) / sizeof(sRegions[0]))

/* Not in the heap, alias or stack region: the kernel refuses code mappings there even where nothing is mapped. */
static int clear_of(uint64_t at, uint64_t size, uint32_t idAddr, uint32_t idSize) {
    uint64_t a = info(idAddr), n = info(idSize);
    return n == 0 || at + size <= a || at >= a + n;
}

static int window_free(uint64_t w) {
    MemoryInfo mi;
    uint32_t pi;

    if (!clear_of(w, GB4, InfoType_HeapRegionAddress, InfoType_HeapRegionSize) ||
        !clear_of(w, GB4, InfoType_AliasRegionAddress, InfoType_AliasRegionSize) ||
        !clear_of(w, GB4, InfoType_StackRegionAddress, InfoType_StackRegionSize)) {
        return 0;
    }
    if (R_FAILED(svcQueryMemory(&mi, &pi, w))) {
        return 0;
    }
    return mi.type == MemType_Unmapped && mi.addr + mi.size >= w + GB4;
}

static uint64_t find_window(void) {
    uint64_t start = info(InfoType_AslrRegionAddress), end = start + info(InfoType_AslrRegionSize), w;

    if (window_free(WINDOW_FIXED)) {
        return WINDOW_FIXED;
    }
    for (w = (start + GB4 - 1) & ~(GB4 - 1); w + GB4 <= end; w += GB4) {
        if (window_free(w)) {
            return w;
        }
    }
    return 0;
}

static Result map_rw(Handle h, uint64_t dst, void *src, uint64_t size) {
    Result rc = svcMapProcessCodeMemory(h, dst, (uint64_t)src, size);

    if (R_SUCCEEDED(rc)) {
        rc = svcSetProcessMemoryPermission(h, dst, size, Perm_Rw);
    }
    return rc;
}

static int test_window(void) {
    Handle h = envGetOwnProcessHandle();
    uint64_t w, i;
    VirtmemReservation *rv = NULL;
    int ok = 1;
    static const uint32_t code[] = {0x52800540u, 0xD65F03C0u}; /* mov w0, #42; ret */
    void *codeSrc;

    say("\n[1] Memory window\n");
    say("  address space %#" PRIx64 " + %#" PRIx64 "\n", info(InfoType_AslrRegionAddress), info(InfoType_AslrRegionSize));
    say("  heap region   %#" PRIx64 " + %#" PRIx64 "\n", info(InfoType_HeapRegionAddress), info(InfoType_HeapRegionSize));
    say("  alias region  %#" PRIx64 " + %#" PRIx64 "\n", info(InfoType_AliasRegionAddress), info(InfoType_AliasRegionSize));
    say("  stack region  %#" PRIx64 " + %#" PRIx64 "\n", info(InfoType_StackRegionAddress), info(InfoType_StackRegionSize));
    say("  memory: %" PRIu64 " MB for this process, %" PRIu64 " MB used\n", info(InfoType_TotalMemorySize) >> 20,
        info(InfoType_UsedMemorySize) >> 20);
    say("  process handle %#x; svcs allowed: MapProcessCodeMemory %d, SetProcessMemoryPermission %d, Unmap %d\n", h,
        envIsSyscallHinted(0x77), envIsSyscallHinted(0x73), envIsSyscallHinted(0x78));

    w = find_window();
    if (w == 0) {
        say("  FAIL: no free 4 GB-aligned window of 4 GB\n");
        return 0;
    }
    say("  window W = %#" PRIx64 "%s\n", w, w == WINDOW_FIXED ? " (the fixed choice is free)" : " (the fixed choice is NOT free)");
    virtmemLock();
    rv = virtmemAddReservation((void *)w, GB4);
    virtmemUnlock();

    for (i = 0; i < NREGIONS; i++) {
        Region *r = &sRegions[i];
        uint64_t at = w + r->addr;
        Result rc;

        r->src = aligned_alloc(0x1000, r->size);
        if (r->src == NULL) {
            say("  FAIL %-26s no memory for %u KB\n", r->what, r->size >> 10);
            ok = 0;
            continue;
        }
        rc = map_rw(h, at, r->src, r->size);
        if (R_FAILED(rc)) {
            say("  FAIL %-26s W+%08X: result %#x\n", r->what, r->addr, rc);
            ok = 0;
            continue;
        }
        r->mapped = 1;
        volatile uint32_t *first = (volatile uint32_t *)at, *last = (volatile uint32_t *)(at + r->size - 4);
        *first = 0xB73DEC00u ^ r->addr;
        *last = ~r->addr;
        if (*first != (0xB73DEC00u ^ r->addr) || *last != ~r->addr || (uint32_t)at != r->addr) {
            say("  FAIL %-26s written and read back wrong\n", r->what);
            ok = 0;
        } else {
            say("  ok   %-26s W+%08X, %u KB\n", r->what, r->addr, r->size >> 10);
        }
    }

    /* the program's own place: code mapped at W + 0x20000000 and run there */
    codeSrc = aligned_alloc(0x1000, 0x1000);
    if (codeSrc != NULL) {
        uint64_t at = w + 0x20000000u;
        Result rc;

        memset(codeSrc, 0, 0x1000);
        memcpy(codeSrc, code, sizeof(code));
        armDCacheFlush(codeSrc, 0x1000);
        rc = svcMapProcessCodeMemory(h, at, (uint64_t)codeSrc, 0x1000);
        if (R_SUCCEEDED(rc)) {
            rc = svcSetProcessMemoryPermission(h, at, 0x1000, Perm_Rx);
            if (R_SUCCEEDED(rc)) {
                armICacheInvalidate((void *)at, 0x1000);
                int got = ((int (*)(void))at)();
                say("  %s code at W+20000000 returned %d (42 expected)\n", got == 42 ? "ok  " : "FAIL", got);
                ok &= got == 42;
            } else {
                say("  FAIL code at W+20000000: permission result %#x\n", rc);
                ok = 0;
            }
            if (R_FAILED(svcUnmapProcessCodeMemory(h, at, (uint64_t)codeSrc, 0x1000))) {
                codeSrc = NULL; /* still aliased: not given back to the heap */
            }
        } else {
            say("  FAIL code at W+20000000: map result %#x\n", rc);
            ok = 0;
        }
        free(codeSrc);
    }

    for (i = 0; i < NREGIONS; i++) {
        Region *r = &sRegions[i];
        if (r->mapped) {
            Result rc = svcUnmapProcessCodeMemory(h, w + r->addr, (uint64_t)r->src, r->size);
            if (R_FAILED(rc)) {
                say("  note: unmapping %s: result %#x\n", r->what, rc);
                continue; /* the memory stays aliased: not given back to the heap */
            }
        }
        free(r->src);
    }
    if (rv != NULL) {
        virtmemLock();
        virtmemRemoveReservation(rv);
        virtmemUnlock();
    }
    say("  memory window: %s\n", ok ? "PASS" : "FAIL");
    return ok;
}

/* ---- 2. speed ---------------------------------------------------------------------------------------- */

static void test_speed(void) {
    BenchResult r;
    ClkrstSession s;
    uint32_t hz = 0;

    say("\n[2] Processor\n");
    if (hosversionAtLeast(8, 0, 0)) {
        if (R_SUCCEEDED(clkrstInitialize())) {
            if (R_SUCCEEDED(clkrstOpenSession(&s, PcvModuleId_CpuBus, 3))) {
                clkrstGetClockRate(&s, &hz);
                clkrstCloseSession(&s);
            }
            clkrstExit();
        }
    } else if (R_SUCCEEDED(pcvInitialize())) {
        pcvGetClockRate(PcvModule_CpuBus, &hz);
        pcvExit();
    }
    say("  CPU clock: %s", hz ? "" : "unknown\n");
    if (hz) {
        say("%u MHz\n", hz / 1000000u);
    }
    Bench_SoftFloat(&r, BENCH_SF_ITERS);
    say("  soft float: %.2f ns per operation (check %08X)\n", (double)r.ns / (double)r.ops, r.sink);
    Bench_Memory(&r, BENCH_MEM_ITERS);
    say("  memory walk: %.2f ns per step (check %08X)\n", (double)r.ns / (double)r.ops, r.sink);
    say("  (the same file on a PC: see the top of port/switch/spike/source/bench.c)\n");
}

/* ---- 3. OpenGL ---------------------------------------------------------------------------------------- */

static EGLDisplay sDisplay;
static EGLContext sContext;
static EGLSurface sSurface;
static int sClipControl;

static int egl_start(void) {
    EGLConfig config;
    EGLint n = 0;
    static const EGLint fb[] = {EGL_RENDERABLE_TYPE, EGL_OPENGL_BIT, EGL_RED_SIZE, 8, EGL_GREEN_SIZE, 8, EGL_BLUE_SIZE, 8,
                                EGL_ALPHA_SIZE, 8, EGL_DEPTH_SIZE, 24, EGL_STENCIL_SIZE, 8, EGL_NONE};
    /* what gs_gl.c asks SDL for: 3.3 core */
    static const EGLint ctx[] = {EGL_CONTEXT_OPENGL_PROFILE_MASK_KHR, EGL_CONTEXT_OPENGL_CORE_PROFILE_BIT_KHR,
                                 EGL_CONTEXT_MAJOR_VERSION_KHR, 3, EGL_CONTEXT_MINOR_VERSION_KHR, 3, EGL_NONE};

    sDisplay = eglGetDisplay(EGL_DEFAULT_DISPLAY);
    if (sDisplay == EGL_NO_DISPLAY || !eglInitialize(sDisplay, NULL, NULL)) {
        say("  FAIL: no EGL display (%#x)\n", eglGetError());
        return 0;
    }
    if (!eglBindAPI(EGL_OPENGL_API) || !eglChooseConfig(sDisplay, fb, &config, 1, &n) || n == 0) {
        say("  FAIL: no OpenGL configuration (%#x)\n", eglGetError());
        return 0;
    }
    sSurface = eglCreateWindowSurface(sDisplay, config, nwindowGetDefault(), NULL);
    if (sSurface == EGL_NO_SURFACE) {
        say("  FAIL: no window surface (%#x)\n", eglGetError());
        return 0;
    }
    sContext = eglCreateContext(sDisplay, config, EGL_NO_CONTEXT, ctx);
    if (sContext == EGL_NO_CONTEXT) {
        say("  FAIL: no OpenGL 3.3 core context (%#x)\n", eglGetError());
        return 0;
    }
    eglMakeCurrent(sDisplay, sSurface, sSurface, sContext);
    gladLoadGL();
    return 1;
}

static void egl_stop(void) {
    if (sDisplay != EGL_NO_DISPLAY) {
        eglMakeCurrent(sDisplay, EGL_NO_SURFACE, EGL_NO_SURFACE, EGL_NO_CONTEXT);
        if (sContext != EGL_NO_CONTEXT) {
            eglDestroyContext(sDisplay, sContext);
        }
        if (sSurface != EGL_NO_SURFACE) {
            eglDestroySurface(sDisplay, sSurface);
        }
        eglTerminate(sDisplay);
    }
    sDisplay = EGL_NO_DISPLAY;
    sContext = EGL_NO_CONTEXT;
    sSurface = EGL_NO_SURFACE;
}

/* The rules of translate() in port/src/gs/gs_gl.c (Vulkan GLSL 450 -> GL 3.3 core), repeated here so that the
   spike builds on its own. Keep the two the same. */
static char *translate(const char *src, int is_vertex) {
    size_t cap = strlen(src) + 256, len = 0;
    char *out = malloc(cap);
    const char *p = src;
#define PUSHN(s, n_) do { size_t _n = (n_); \
    while (len + _n + 1 > cap) { cap *= 2; } out = realloc(out, cap); memcpy(out + len, (s), _n); len += _n; } while (0)
#define PUSH(str) PUSHN((str), strlen(str))
    while (*p) {
        if (!strncmp(p, "#version 450", 12)) { PUSH("#version 330 core"); p += 12; continue; }
        if (!strncmp(p, "gl_VertexIndex", 14)) { PUSH("gl_VertexID"); p += 14; continue; }
        if (!strncmp(p, "layout(depth_less)", 18)) { while (*p && *p != '\n') { p++; } continue; }
        if (!strncmp(p, "layout(set", 10)) {
            const char *e = strchr(p, ')');
            if (e) { p = e + 1; if (*p == ' ') p++; continue; }
        }
        if (!strncmp(p, "layout(location", 15)) {
            const char *e = strchr(p, ')');
            if (e) {
                const char *q = e + 1;
                while (*q == ' ' || *q == '\t') q++;
                int in_out = !strncmp(q, "in ", 3) || !strncmp(q, "out ", 4);
                int bad = in_out && (is_vertex ? !strncmp(q, "out ", 4) : !strncmp(q, "in ", 3));
                if (bad) { p = q; continue; }
                PUSHN(p, (size_t)(e + 1 - p));
                p = e + 1;
                continue;
            }
        }
        PUSHN(p, 1);
        p++;
    }
    out[len] = 0;
    if (is_vertex) {
        char *m = strstr(out, "void main");
        if (m != NULL) {
            size_t rest = strlen(m + 5) + 1;
            while (len + 4 > cap) cap *= 2;
            size_t off = (size_t)(m - out);
            out = realloc(out, cap);
            m = out + off;
            memmove(m + 8, m + 5, rest);
            memcpy(m + 5, "gs_", 3);
            len += 3;
        }
        PUSH(sClipControl ? "\nvoid main() { gs_main(); gl_Position.y = -gl_Position.y; }\n"
                          : "\nvoid main() { gs_main(); gl_Position.y = -gl_Position.y; gl_Position.z = 2.0 * gl_Position.z - gl_Position.w; }\n");
        out[len] = 0;
    }
#undef PUSH
#undef PUSHN
    return out;
}

static GLuint compile(GLenum stage, const char *src, const char *tag, int *ok) {
    GLuint sh = glCreateShader(stage);
    GLint good = 0;
    char *t = translate(src, stage == GL_VERTEX_SHADER);

    glShaderSource(sh, 1, (const GLchar *const *)&t, NULL);
    glCompileShader(sh);
    glGetShaderiv(sh, GL_COMPILE_STATUS, &good);
    free(t);
    if (!good) {
        char log[512];
        glGetShaderInfoLog(sh, sizeof(log), NULL, log);
        say("  FAIL %s (%s): %s\n", tag, stage == GL_VERTEX_SHADER ? "vertex" : "fragment", log);
        *ok = 0;
    }
    return sh;
}

static int program(const char *vs, const char *fs, const char *tag) {
    int ok = 1;
    uint64_t t0 = Bench_NowNs();
    GLuint v = compile(GL_VERTEX_SHADER, vs, tag, &ok), f = compile(GL_FRAGMENT_SHADER, fs, tag, &ok), p;
    GLint linked = 0;

    if (!ok) {
        return 0;
    }
    p = glCreateProgram();
    glAttachShader(p, v);
    glAttachShader(p, f);
    glLinkProgram(p);
    glGetProgramiv(p, GL_LINK_STATUS, &linked);
    if (!linked) {
        char log[512];
        glGetProgramInfoLog(p, sizeof(log), NULL, log);
        say("  FAIL %s (link): %s\n", tag, log);
        return 0;
    }
    say("  ok   %-9s %4" PRIu64 " ms\n", tag, (Bench_NowNs() - t0) / 1000000u);
    return 1;
}

static int test_gl(void) {
    int ok = 1, i;
    GLint major = 0, minor = 0, n = 0;

    say("\n[3] OpenGL\n");
    if (!egl_start()) {
        egl_stop();
        return 0;
    }
    glGetIntegerv(GL_MAJOR_VERSION, &major);
    glGetIntegerv(GL_MINOR_VERSION, &minor);
    say("  %s\n  %s\n  GLSL %s\n", (const char *)glGetString(GL_VERSION), (const char *)glGetString(GL_RENDERER),
        (const char *)glGetString(GL_SHADING_LANGUAGE_VERSION));
    glGetIntegerv(GL_NUM_EXTENSIONS, &n);
    for (i = 0; i < n; i++) {
        if (!strcmp((const char *)glGetStringi(GL_EXTENSIONS, (GLuint)i), "GL_ARB_clip_control")) {
            sClipControl = 1;
        }
    }
    sClipControl |= major > 4 || (major == 4 && minor >= 5);
    say("  context %d.%d core, clip control %s\n", major, minor, sClipControl ? "yes" : "no");

    /* the programs of gs_gl.c, in its order */
    ok &= program(kGsVert, kGsFrag, "gs");
    ok &= program(kVu0Vert, kGsFrag, "vu0");
    ok &= program(kVu4Vert, kGsFrag, "vu4");
    ok &= program(kVu6Vert, kGsFrag, "vu6");
    ok &= program(kGsVert, kGsnzFrag, "gs nz");
    ok &= program(kVu0Vert, kGsnzFrag, "vu0 nz");
    ok &= program(kVu4Vert, kGsnzFrag, "vu4 nz");
    ok &= program(kVu6Vert, kGsnzFrag, "vu6 nz");
    ok &= program(kGsVert, kGswbFrag, "gs wb");
    ok &= program(kFxVert, kOutlineFrag, "outline");
    ok &= program(kFxVert, kAlphakeyFrag, "alphakey");
    ok &= program(kFxVert, kDclutFrag, "dclut");

    /* one picture to the screen (orange, the setup window's colour) */
    glViewport(0, 0, 1280, 720);
    glClearColor(0.96f, 0.55f, 0.13f, 1.0f);
    glClear(GL_COLOR_BUFFER_BIT);
    ok &= eglSwapBuffers(sDisplay, sSurface) == EGL_TRUE;
    ok &= glGetError() == GL_NO_ERROR;
    egl_stop();
    say("  OpenGL: %s\n", ok ? "PASS" : "FAIL");
    return ok;
}

/* ---- the program ----------------------------------------------------------------------------------------- */

int main(int argc, char **argv) {
    PadState pad;
    int mem, gl;
    FILE *f;

    (void)argc;
    (void)argv;
    consoleInit(NULL);
    sConsole = 1;
    padConfigureInput(1, HidNpadStyleSet_NpadStandard);
    padInitializeDefault(&pad);

    say("Tenkaichi3Decomp - Switch spike (docs/port/switch_plan.md)\n");
    say("running as %s, system %u.%u.%u%s\n", appletGetAppletType() == AppletType_Application ? "an application" : "an applet",
        HOSVER_MAJOR(hosversionGet()), HOSVER_MINOR(hosversionGet()), HOSVER_MICRO(hosversionGet()),
        hosversionIsAtmosphere() ? ", Atmosphere" : "");
    mem = test_window();
    test_speed();

    /* the console and EGL both draw to the screen: the console is put away during the OpenGL test */
    say("\n(the OpenGL test takes the screen for a moment)\n");
    consoleExit(NULL);
    sConsole = 0;
    gl = test_gl();
    consoleInit(NULL);
    fputs(sLog, stdout); /* everything again: the console was cleared */
    sConsole = 1;

    say("\nSummary: memory window %s, OpenGL %s.\n", mem ? "PASS" : "FAIL", gl ? "PASS" : "FAIL");
    f = fopen(LOG_PATH, "w");
    if (f != NULL) {
        fwrite(sLog, 1, sLogLen, f);
        fclose(f);
        say("Written to %s.\n", LOG_PATH);
    } else {
        say("Could not write %s.\n", LOG_PATH);
    }
    say("Press + to exit.\n");

    while (appletMainLoop()) {
        padUpdate(&pad);
        if (padGetButtonsDown(&pad) & HidNpadButton_Plus) {
            break;
        }
        consoleUpdate(NULL);
    }
    consoleExit(NULL);
    return 0;
}
