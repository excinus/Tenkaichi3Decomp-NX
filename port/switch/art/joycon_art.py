"""The picture of the options screen's controller page for the Switch: a pair of Joy-Con (joycons.svg, the player's
drawing) where the game shows a DualShock 2. Writes port/src/nx_joycon_art.h, which port/src/plat_nxart.c puts in
place of the PS2 pad's picture, a 128 x 128 texture of 256 colours, when the options screen is unpacked.

    .venv/bin/python port/switch/art/joycon_art.py [preview.png]

(needs cairosvg: .venv/bin/pip install cairosvg)

Size and place, measured on a console's screenshots: the texture is shown a GS pixel a texel, between the page's
title and the guide's head under it; the Joy-Con stand 116 texels high from texel 6, centred across. A GS pixel is
not square on the screen: the menus' 512 x 448 picture fills a 4:3 or a 16:9 page (the setting "Menus"), so a texel
is 1.17 or 1.56 times as wide as high. Two pictures are made, the drawing narrowed for each so that it shows in its
own shape (the first one, square texels, looked squashed on a 16:9 page), and plat_nxart.c takes the one of the page.
"""
import io, sys
from pathlib import Path
import numpy as np
import cairosvg
from PIL import Image

HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent / "src" / "nx_joycon_art.h"
N, TOP, HIGH, SS = 128, 6, 116, 8
PAGES = (1333, 1778)  # the page's shape, width / height x 1000: 4:3 and 16:9

def picture(page):
    svg = (HERE / "joycons.svg").read_bytes()
    big = Image.open(io.BytesIO(cairosvg.svg2png(bytestring=svg, output_height=HIGH * SS * 2))).convert("RGBA")
    big = big.crop(big.getbbox())                                    # the drawing itself, not the page round it
    texel = page / 1000 * 448 / 512                                  # a texel's width on the screen, its height 1
    w = round(HIGH * big.width / big.height / texel)
    small = big.convert("RGBa").resize((w, HIGH), Image.LANCZOS).convert("RGBA")  # (premultiplied: clean edges)
    out = Image.new("RGBA", (N, N), (0, 0, 0, 0))
    out.alpha_composite(small, ((N - w) // 2, TOP))
    return out

def quantized(img):
    q = img.quantize(colors=256, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE)
    pal = np.zeros((256, 4), dtype=int)
    raw = np.array(q.getpalette(rawmode="RGBA")).reshape(-1, 4)
    pal[:len(raw)] = raw
    idx = np.array(q, dtype=np.uint8)
    clear = np.array(img.getchannel("A")) == 0
    if clear.any():                                                   # fully clear texels: one clear entry
        k = int(np.argmin(pal[:, 3] * 1000 + pal[:, :3].sum(1)))
        pal[k] = (0, 0, 0, 0)
        idx[clear] = k
    pal[:, 3] = (pal[:, 3] * 128 + 127) // 255                       # the GS's alpha: 128 is opaque
    return idx, pal

def main():
    lines = ["/* Generated by port/switch/art/joycon_art.py from joycons.svg: the Joy-Con picture of the options screen's\n",
             "   controller page (port/src/plat_nxart.c), 128 x 128 texels of 256 colours, the GS's alpha (0..128), one for\n",
             "   each shape of the page (kJoyconPage: width / height x 1000). */\n",
             "static const int kJoyconPage[%d] = {%s};\n" % (len(PAGES), ", ".join(str(p) for p in PAGES)),
             "static const unsigned char kJoyconIdx[%d][128 * 128] = {\n" % len(PAGES)]
    pals, previews = [], []
    for page in PAGES:
        img = picture(page)
        idx, pal = quantized(img)
        pals.append(pal)
        lines.append("  {\n")
        flat = idx.reshape(-1)
        for i in range(0, len(flat), 32):
            lines.append("    " + ",".join(str(v) for v in flat[i:i + 32]) + ",\n")
        lines.append("  },\n")
        shown = pal.astype(np.uint8)[idx].copy()
        shown[..., 3] = np.minimum(255, shown[..., 3].astype(int) * 255 // 128)
        texel = page / 1000 * 448 / 512                              # (the preview as the page shows it)
        bg = Image.new("RGBA", (N, N), (20, 34, 70, 255))
        bg.alpha_composite(Image.fromarray(shown, "RGBA"))
        previews.append(bg.convert("RGB").resize((round(N * 3 * texel), N * 3), Image.NEAREST))
        print("page %d: picture %s" % (page, img.getbbox()))
    lines.append("};\nstatic const unsigned char kJoyconPal[%d][256][4] = {\n" % len(PAGES))
    for pal in pals:
        lines.append("  {\n")
        for i in range(0, 256, 8):
            lines.append("    " + ", ".join("{%d, %d, %d, %d}" % tuple(pal[j]) for j in range(i, i + 8)) + ",\n")
        lines.append("  },\n")
    lines.append("};\n")
    OUT.write_text("".join(lines))
    print("wrote", OUT)
    if len(sys.argv) > 1:                                          # the two side by side, as the pages show them
        sheet = Image.new("RGB", (sum(p.width for p in previews) + 20, previews[0].height), (0, 0, 0))
        x = 0
        for p in previews:
            sheet.paste(p, (x, 0))
            x += p.width + 20
        sheet.save(sys.argv[1])

if __name__ == "__main__":
    main()
